#!/usr/bin/env node
// Generates circuits/fixtures/*.json (spec cross-check vectors).
// Fields: decimal strings. Bytes: lowercase hex (no 0x).
// Usage: node scripts/gen-fixtures.mjs [--no-proofs]
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  initPoseidon, poseidon, zeros, MerkleTree, mintField, extDataHash, extDataBytes, toBE32, toHex,
  encodePublicInputs, proofToHex, WSOL_MINT, USDC_MINT, USDT_MINT, P,
} from '../lib/index.js';
import { buildScenario, detField, detPubkey, detBlob } from '../lib/scenario.js';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '..', 'fixtures');
mkdirSync(outDir, { recursive: true });
const S = (x) => BigInt(x).toString();
const hex32 = (x) => toHex(toBE32(BigInt(x)));
const write = (name, obj) => {
  writeFileSync(join(outDir, name), JSON.stringify(obj, null, 2) + '\n');
  console.log(`wrote fixtures/${name}`);
};
const extDataJson = (e) => ({
  recipient: e.recipient, relayer: e.relayer, extAmount: S(e.extAmount), fee: S(e.fee),
  encryptedOutput1: e.encryptedOutput1, encryptedOutput2: e.encryptedOutput2,
  encryptedSwapOutput: e.encryptedSwapOutput ?? '00'.repeat(87),
});

await initPoseidon();
const NOTE = 'Generated by circuits/scripts/gen-fixtures.mjs. Fields are decimal strings; bytes are hex; field elements on-chain are 32-byte big-endian.';

// ---- poseidon.json ----
const posVectors = [
  [1n], [0n], [1n, 2n], [0n, 0n], [1n, 2n, 3n], [1n, 2n, 3n, 4n],
  [P - 1n], [detField('pa'), detField('pb')], [detField('pc'), detField('pd'), detField('pe')],
  [123456789n, detField('pk'), detField('bl'), mintField(WSOL_MINT)],
].map((inputs) => ({ inputs: inputs.map(S), output: S(poseidon(inputs)), outputHex: hex32(poseidon(inputs)) }));
write('poseidon.json', { note: NOTE + ' circomlib Poseidon (light-poseidon Bn254X5 circom params).', vectors: posVectors });

// ---- zeros.json ----
const z = zeros(20);
write('zeros.json', { note: NOTE + ' zeros[0]=0, zeros[i+1]=Poseidon(zeros[i],zeros[i]); zeros[20] is the empty-tree root.',
  depth: 20, zeros: z.map(S), zerosHex: z.map(hex32), emptyRoot: S(z[20]), emptyRootHex: hex32(z[20]) });

// ---- merkle.json ----
{
  const t = new MerkleTree();
  const leaves = Array.from({ length: 6 }, (_, i) => poseidon([BigInt(i + 1), detField('leaf' + i)]));
  const inserts = [];
  for (let i = 0; i < leaves.length; i += 2) {
    t.insertPair(leaves[i], leaves[i + 1]);
    inserts.push({ leaves: [S(leaves[i]), S(leaves[i + 1])], indices: [i, i + 1], rootAfter: S(t.root()), rootAfterHex: hex32(t.root()), nextIndex: t.nextIndex });
  }
  // also single-leaf roots (each step) for implementations that append one at a time
  const t1 = new MerkleTree();
  const singles = leaves.map((l) => { t1.insert(l); return { leaf: S(l), index: t1.nextIndex - 1, rootAfter: S(t1.root()) }; });
  const idx = 3;
  const p = t.path(idx);
  write('merkle.json', {
    note: NOTE + ' Depth 20, Poseidon(left,right). pairInserts mirror transact (two leaves per instruction). Path: pathElements are siblings bottom-up; bit i of index = 1 means the node at level i is the right child.',
    depth: 20, initialRoot: S(z[20]), pairInserts: inserts, singleInserts: singles,
    path: { leafIndex: idx, leaf: S(leaves[idx]), pathElements: p.pathElements.map(S), pathIndices: idx, root: S(p.root) },
  });
}

// ---- extdata.json ----
{
  const cases = [
    { name: 'deposit', recipient: detPubkey('x-alice'), relayer: detPubkey('x-alice'), extAmount: 1_000_000_000n, fee: 0n,
      encryptedOutput1: detBlob('x1'), encryptedOutput2: detBlob('x2'), encryptedSwapOutput: '00'.repeat(87) },
    { name: 'withdraw', recipient: detPubkey('x-bob'), relayer: detPubkey('x-relayer'), extAmount: -123_456_789n, fee: 5_000n,
      encryptedOutput1: detBlob('x3'), encryptedOutput2: detBlob('x4'), encryptedSwapOutput: '00'.repeat(87) },
    { name: 'transfer', recipient: WSOL_MINT, relayer: detPubkey('x-relayer'), extAmount: 0n, fee: 1n,
      encryptedOutput1: detBlob('x5'), encryptedOutput2: detBlob('x6'), encryptedSwapOutput: '00'.repeat(87) },
    { name: 'swap', recipient: detPubkey('x-escrow'), relayer: detPubkey('x-relayer'), extAmount: -(2n ** 63n), fee: 2n ** 64n - 1n,
      encryptedOutput1: detBlob('x7'), encryptedOutput2: detBlob('x8'), encryptedSwapOutput: detBlob('x9') },
    { name: 'extremes', recipient: '11111111111111111111111111111111', relayer: USDT_MINT, extAmount: 2n ** 63n - 1n, fee: 0n,
      encryptedOutput1: 'ff'.repeat(87), encryptedOutput2: '00'.repeat(87), encryptedSwapOutput: '00'.repeat(87) },
  ];
  write('extdata.json', {
    note: NOTE + ' extDataHash = sha256(recipient32 ++ relayer32 ++ extAmount i64 LE ++ fee u64 LE ++ enc1(87) ++ enc2(87) ++ encSwap(87)) with byte 0 set to 0, read big-endian.',
    cases: cases.map(({ name, ...e }) => {
      const h = extDataHash(e);
      return { name, extData: extDataJson(e), preimageHex: toHex(extDataBytes(e)), extDataHash: S(h.value), extDataHashHex: h.hex };
    }),
  });
}

// ---- mint.json ----
write('mint.json', {
  note: NOTE + ' mintField = first 31 bytes of the mint pubkey as big-endian; 32-byte form = 0x00 ++ mint[0..31].',
  mints: [['wSOL', WSOL_MINT], ['USDC', USDC_MINT], ['USDT', USDT_MINT]].map(([symbol, mint]) => ({
    symbol, mint, mintField: S(mintField(mint)), mintFieldHex: hex32(mintField(mint)),
  })),
});

// ---- proofs.json ----
if (!process.argv.includes('--no-proofs')) {
  const { prove, verify, loadVk, terminate, VK } = await import('../lib/prover.js');
  const vk = loadVk();
  const sc = buildScenario();
  const out = [];
  for (const st of sc.steps) {
    const t0 = Date.now();
    const { proof, publicSignals } = await prove(st.witness.input);
    const ms = Date.now() - t0;
    if (JSON.stringify(publicSignals) !== JSON.stringify(st.witness.publicSignals)) throw new Error(`${st.name}: public signal mismatch`);
    if (!(await verify(publicSignals, proof, vk))) throw new Error(`${st.name}: proof does not verify`);
    console.log(`  ${st.name}: proved in ${ms} ms, verified`);
    const w = st.witness;
    const edh = extDataHash(st.extData);
    out.push({
      name: st.name,
      flow: st.flow,
      mint: st.mint,
      mintField: S(sc.mintField),
      swapMint: st.swapMint,
      publicSignals,
      publicInputsHex: encodePublicInputs(publicSignals).map(toHex),
      ...proofToHex(proof),
      snarkjsProof: proof,
      extData: extDataJson(st.extData),
      extDataHash: S(edh.value),
      extDataHashHex: edh.hex,
      publicAmount: S(w.publicAmount),
      root: S(w.root),
      rootHex: hex32(w.root),
      leavesBefore: st.leavesBefore.map(S),
      leavesAfter: st.leavesAfter.map(S),
      inputNullifiersHex: publicSignals.slice(4, 6).map(hex32),
      outputCommitmentsHex: publicSignals.slice(6, 8).map(hex32),
      swapCommitmentHex: hex32(publicSignals[10]),
      provingTimeMs: ms,
    });
  }
  write('proofs.json', {
    note: NOTE + ' DEV zkey (UNSAFE). Proofs run in sequence on one SOL pool tree: leavesBefore is the tree state the proof uses (root = root of leavesBefore), leavesAfter adds the two output commitments. proofA is the NEGATED pi_a (x ++ (q - y)); proofB = x.c1 ++ x.c0 ++ y.c1 ++ y.c0; proofC = x ++ y. publicInputsHex are the 11 groth16-solana public inputs in §4 order. The swap recipient is a placeholder, not the real escrow PDA.',
    zkey: 'assets/zk/transaction_final.zkey',
    verificationKeySha256: createHash('sha256').update(readFileSync(VK)).digest('hex'),
    proofs: out,
  });
  await terminate();
}
