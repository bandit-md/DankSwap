#!/usr/bin/env node
// Converts a snarkjs verification_key.json into
// programs/dankswap-pool/src/verifying_key.rs for groth16-solana 0.2.
//
// Byte conventions (same as groth16-solana's parse_vk_to_rust.js):
//   G1: x(32 BE) ++ y(32 BE)
//   G2: x.c1 ++ x.c0 ++ y.c1 ++ y.c0 (each 32 BE); snarkjs stores [c0, c1].
//
// Usage: node scripts/vk-to-rust.mjs [verification_key.json] [out.rs]

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { g1ToBytes, g2ToBytes } from '../lib/encode.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const vkPath = process.argv[2] || join(root, 'build', 'verification_key.json');
const outPath = process.argv[3] || resolve(root, '..', 'programs', 'dankswap-pool', 'src', 'verifying_key.rs');

export function vkToRust(vk) {
  if (vk.protocol !== 'groth16' || vk.curve !== 'bn128') throw new Error('expected groth16 / bn128 vk');
  const fmt = (bytes, indent) => {
    const lines = [];
    for (let i = 0; i < bytes.length; i += 16) lines.push(indent + Array.from(bytes.slice(i, i + 16)).join(', ') + ',');
    return lines.join('\n');
  };
  const g1 = (p, ind) => `[\n${fmt(g1ToBytes(p), ind + '    ')}\n${ind}]`;
  const g2 = (p, ind) => `[\n${fmt(g2ToBytes(p), ind + '    ')}\n${ind}]`;
  const ic = vk.IC.map((p) => `        ${g1(p, '        ')},`).join('\n');
  return `// @generated by circuits/scripts/vk-to-rust.mjs from circuits/build/verification_key.json.
// DO NOT EDIT BY HAND. Regenerate with \`cd circuits && npm run build\` (or \`npm run vk:rust\`).
//
// DEV TRUSTED SETUP (single local contributor): UNSAFE FOR REAL FUNDS.
// Circuit: Transaction(20, 2, 2), ${vk.nPublic} public inputs in spec §4 order.
// G1 = x||y (32-byte BE each); G2 = x.c1||x.c0||y.c1||y.c0 (32-byte BE each).

use groth16_solana::groth16::Groth16Verifyingkey;

pub const VERIFYINGKEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${g1(vk.vk_alpha_1, '    ')},
    vk_beta_g2: ${g2(vk.vk_beta_2, '    ')},
    vk_gamme_g2: ${g2(vk.vk_gamma_2, '    ')},
    vk_delta_g2: ${g2(vk.vk_delta_2, '    ')},
    vk_ic: &[
${ic}
    ],
};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const vk = JSON.parse(readFileSync(vkPath, 'utf8'));
  if (vk.IC.length !== vk.nPublic + 1) throw new Error('IC length mismatch');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, vkToRust(vk));
  console.log(`wrote ${outPath} (nr_pubinputs=${vk.nPublic}, vk_ic=${vk.IC.length})`);
}
