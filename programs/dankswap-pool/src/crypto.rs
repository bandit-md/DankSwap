/// circomlib-compatible Poseidon over 32-byte big-endian field elements.
/// On-chain this is the `sol_poseidon` syscall; on the host it is light-poseidon.
pub fn poseidon(inputs: &[&[u8]]) -> Result<[u8; 32]> {
    hashv(Parameters::Bn254X5, Endianness::BigEndian, inputs)
        .map(|h| h.to_bytes())
        .map_err(|_| error!(PoolError::PoseidonError))
}

/// `mintField(mint)` = first 31 bytes of the mint as a BE integer = `[0x00] ++ mint[0..31]`.
pub fn mint_field(mint: &Pubkey) -> [u8; 32] {
    let mut out = [0u8; 32];
    out[1..].copy_from_slice(&mint.to_bytes()[..31]);
    out
}

/// u64 as a 32-byte big-endian field element.
pub fn u64_to_field(x: u64) -> [u8; 32] {
    let mut out = [0u8; 32];
    out[24..].copy_from_slice(&x.to_be_bytes());
    out
}

/// `publicAmount = (extAmount - fee) mod p` as 32-byte big-endian.
/// Negative values are encoded as `p - |x|`.
pub fn public_amount(ext_amount: i64, fee: u64) -> Result<[u8; 32]> {
    let x = (ext_amount as i128)
        .checked_sub(fee as i128)
        .ok_or(error!(PoolError::MathOverflow))?;
    let mag = x.unsigned_abs(); // < 2^65, far below p
    let mut mag_be = [0u8; 32];
    mag_be[16..].copy_from_slice(&mag.to_be_bytes());
    if x >= 0 {
        return Ok(mag_be);
    }
    // p - mag, big-endian byte-wise subtraction with borrow (mag < p, mag > 0).
    let mut out = [0u8; 32];
    let mut borrow = 0i16;
    for i in (0..32).rev() {
        let mut d = FIELD_MODULUS_BE[i] as i16 - mag_be[i] as i16 - borrow;
        if d < 0 {
            d += 256;
            borrow = 1;
        } else {
            borrow = 0;
        }
        out[i] = d as u8;
    }
    Ok(out)
}

/// `extDataHash` (spec §5):
/// sha256(recipient ++ relayer ++ extAmount i64 LE ++ fee u64 LE ++ enc1 ++ enc2 ++ encSwap),
/// then byte 0 set to 0x00 (so it is < p), read big-endian.
pub fn ext_data_hash(
    recipient: &Pubkey,
    relayer: &Pubkey,
    ext_amount: i64,
    fee: u64,
    encrypted_output1: &[u8; ENC_LEN],
    encrypted_output2: &[u8; ENC_LEN],
    encrypted_swap_output: &[u8; ENC_LEN],
) -> [u8; 32] {
    let ext = ext_amount.to_le_bytes();
    let fee = fee.to_le_bytes();
    let mut h = solana_sha256_hasher::hashv(&[
        recipient.as_ref(),
        relayer.as_ref(),
        &ext,
        &fee,
        encrypted_output1,
        encrypted_output2,
        encrypted_swap_output,
    ])
    .to_bytes();
    h[0] = 0;
    h
}

/// Plain-data view of the on-chain tree used by the Merkle logic (the zero-copy
/// account type `MerkleTree` derefs to the same fields).
pub trait TreeState {
    fn filled_subtrees(&mut self) -> &mut [[u8; 32]; TREE_DEPTH];
    fn roots(&mut self) -> &mut [[u8; 32]; ROOT_HISTORY_SIZE];
    fn roots_ref(&self) -> &[[u8; 32]; ROOT_HISTORY_SIZE];
    fn current_root_index(&mut self) -> &mut u64;
    fn next_index(&mut self) -> &mut u64;
}

/// Reset to the empty tree: filled_subtrees = zeros[0..20], roots[0] = zeros[20].
pub fn tree_init<T: TreeState>(t: &mut T) {
    for i in 0..TREE_DEPTH {
        t.filled_subtrees()[i] = ZEROS[i];
    }
    *t.roots() = [[0u8; 32]; ROOT_HISTORY_SIZE];
    t.roots()[0] = ZEROS[TREE_DEPTH];
    *t.current_root_index() = 0;
    *t.next_index() = 0;
}

/// Append one leaf at `next_index` (Tornado `filledSubtrees` algorithm) and
/// return the resulting root. Does NOT push the root into the history; call
/// [`tree_push_root`] once per instruction after all appends.
pub fn tree_append<T: TreeState>(t: &mut T, leaf: &[u8; 32]) -> Result<([u8; 32], u64)> {
    let index = *t.next_index();
    require!(index < (1u64 << TREE_DEPTH), PoolError::TreeFull);
    let mut cur = *leaf;
    let mut idx = index;
    for level in 0..TREE_DEPTH {
        let (left, right) = if idx & 1 == 0 {
            t.filled_subtrees()[level] = cur;
            (cur, ZEROS[level])
        } else {
            (t.filled_subtrees()[level], cur)
        };
        cur = poseidon(&[&left, &right])?;
        idx >>= 1;
    }
    *t.next_index() = index + 1;
    Ok((cur, index))
}

/// Store `root` as the newest entry in the 100-root ring.
pub fn tree_push_root<T: TreeState>(t: &mut T, root: [u8; 32]) {
    let next = (*t.current_root_index() + 1) % ROOT_HISTORY_SIZE as u64;
    *t.current_root_index() = next;
    t.roots()[next as usize] = root;
}

/// True if `root` is non-zero and one of the stored roots.
pub fn tree_is_known_root<T: TreeState>(t: &T, root: &[u8; 32]) -> bool {
    if root.iter().all(|b| *b == 0) {
        return false;
    }
    t.roots_ref().iter().any(|r| r == root)
}

/// Assemble the 11 Groth16 public inputs in spec §4 order.
#[allow(clippy::too_many_arguments)]
pub fn build_public_inputs(
    root: &[u8; 32],
    public_amount: &[u8; 32],
    ext_data_hash: &[u8; 32],
    mint_field: &[u8; 32],
    input_nullifiers: &[[u8; 32]; 2],
    output_commitments: &[[u8; 32]; 2],
    swap_mint_field: &[u8; 32],
    swap_amount: &[u8; 32],
    swap_commitment: &[u8; 32],
) -> [[u8; 32]; NR_PUBLIC_INPUTS] {
    [
        *root,
        *public_amount,
        *ext_data_hash,
        *mint_field,
        input_nullifiers[0],
        input_nullifiers[1],
        output_commitments[0],
        output_commitments[1],
        *swap_mint_field,
        *swap_amount,
        *swap_commitment,
    ]
}

/// Verify a Groth16 proof against the generated verifying key.
/// `proof_a` must already be negated by the client (spec §7). Public inputs
/// are range-checked (< p) by groth16-solana, which also rules out
/// non-canonical nullifier encodings (nullifier PDAs are keyed by raw bytes).
#[inline(never)]
pub fn verify_groth16(
    proof_a: &[u8; 64],
    proof_b: &[u8; 128],
    proof_c: &[u8; 64],
    public_inputs: &[[u8; 32]; NR_PUBLIC_INPUTS],
) -> Result<()> {
    let mut verifier = groth16_solana::groth16::Groth16Verifier::new(
        proof_a,
        proof_b,
        proof_c,
        public_inputs,
        &crate::verifying_key::VERIFYINGKEY,
    )
    .map_err(|_| error!(PoolError::InvalidProof))?;
    verifier.verify().map_err(|_| error!(PoolError::InvalidProof))
}
