#!/usr/bin/env node
// Reproduces the pre-bundled third-party files used by the private pool (docs/PHASE2_SPEC.md §10):
//
//   assets/vendor/snarkjs.min.js      snarkjs 0.7.5 browser build, copied as-is (GPL-3.0)
//   assets/vendor/poseidon.bundle.js  circomlib Poseidon (BN254, circom parameters, 1-4 inputs)
//                                     as a pure-BigInt ES module. Constants come from circomlibjs
//                                     0.1.7 (poseidon_constants_opt.js); algorithm = circomlibjs
//                                     poseidon_opt.js. No WebAssembly, so it runs under a strict CSP.
//   assets/vendor/tweetnacl.min.js    tweetnacl 1.0.3 as an ES module (default export = nacl)
//   assets/vendor/*.LICENSE           upstream licence texts
//
// Usage: node scripts/bundle-vendor.mjs
// Pinned packages are installed into a cache folder (VENDOR_CACHE, default: OS temp dir) unless
// VENDOR_NODE_MODULES points at a node_modules folder that already has them.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'assets', 'vendor');
const PINS = { snarkjs: '0.7.5', circomlibjs: '0.1.7', tweetnacl: '1.0.3', esbuild: '0.24.0' };

function modulesDir() {
  if (process.env.VENDOR_NODE_MODULES) return resolve(process.env.VENDOR_NODE_MODULES);
  const cache = resolve(process.env.VENDOR_CACHE || join(tmpdir(), 'dankswap-vendor'));
  const nm = join(cache, 'node_modules');
  const ok = Object.entries(PINS).every(([n, v]) => {
    try {
      return JSON.parse(readFileSync(join(nm, n, 'package.json'), 'utf8')).version === v;
    } catch (_) {
      return false;
    }
  });
  if (!ok) {
    mkdirSync(cache, { recursive: true });
    if (!existsSync(join(cache, 'package.json'))) writeFileSync(join(cache, 'package.json'), '{"private":true}\n');
    const specs = Object.entries(PINS).map(([n, v]) => `${n}@${v}`);
    console.log('Installing', specs.join(' '), 'into', cache);
    execFileSync('npm', ['install', '--no-audit', '--no-fund', '--save-exact', ...specs], { cwd: cache, stdio: 'inherit' });
  }
  return nm;
}

function version(nm, name) {
  return JSON.parse(readFileSync(join(nm, name, 'package.json'), 'utf8')).version;
}

async function main() {
  const nm = modulesDir();
  for (const [n, v] of Object.entries(PINS)) {
    if (n !== 'esbuild' && version(nm, n) !== v) throw new Error(`${n} ${version(nm, n)} found, ${v} required`);
  }
  mkdirSync(OUT, { recursive: true });
  const esbuild = await import(pathToFileURL(join(nm, 'esbuild', 'lib', 'main.js')).href);

  // 1. snarkjs: copy the upstream minified browser build (defines the global `snarkjs`).
  copyFileSync(join(nm, 'snarkjs', 'build', 'snarkjs.min.js'), join(OUT, 'snarkjs.min.js'));
  copyFileSync(join(nm, 'snarkjs', 'COPYING'), join(OUT, 'snarkjs.LICENSE'));

  // 2. Poseidon: constants for t = 2..5 (1-4 inputs) from circomlibjs, pure BigInt arithmetic.
  const { default: opt } = await import(pathToFileURL(join(nm, 'circomlibjs', 'src', 'poseidon_constants_opt.js')).href);
  const pick = (k) => opt[k].slice(0, 4);
  const consts = { C: pick('C'), S: pick('S'), M: pick('M'), P: pick('P') };
  const poseidonSrc = `// circomlib Poseidon over BN254 (circom parameters), 1-4 inputs. Pure BigInt, no WebAssembly.
// Generated by scripts/bundle-vendor.mjs from circomlibjs ${version(nm, 'circomlibjs')} (GPL-3.0):
// constants = src/poseidon_constants_opt.js (t = 2..5), algorithm = src/poseidon_opt.js.
const P = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const RAW = ${JSON.stringify(consts)};
const N_ROUNDS_F = 8;
const N_ROUNDS_P = [56, 57, 56, 60];
const big = (x) => (Array.isArray(x) ? x.map(big) : BigInt(x));
const K = { C: big(RAW.C), S: big(RAW.S), M: big(RAW.M), P: big(RAW.P) };
const add = (a, b) => { const s = a + b; return s >= P ? s - P : s; };
const mul = (a, b) => (a * b) % P;
const pow5 = (a) => { const a2 = mul(a, a); return mul(a, mul(a2, a2)); };
function mix(state, M) {
  const t = state.length;
  const out = new Array(t);
  for (let i = 0; i < t; i++) {
    let acc = 0n;
    for (let j = 0; j < t; j++) acc += M[j][i] * state[j];
    out[i] = acc % P;
  }
  return out;
}
/** Poseidon hash of 1-4 field elements (bigint | number | decimal or 0x string). Returns a bigint. */
export function poseidon(inputs) {
  if (!Array.isArray(inputs) || inputs.length < 1 || inputs.length > 4) throw new Error('poseidon: 1-4 inputs supported');
  const t = inputs.length + 1;
  const nRoundsP = N_ROUNDS_P[t - 2];
  const C = K.C[t - 2], S = K.S[t - 2], M = K.M[t - 2], PM = K.P[t - 2];
  let state = [0n, ...inputs.map((x) => {
    const v = BigInt(x);
    if (v < 0n || v >= P) throw new Error('poseidon: input is not a field element');
    return v;
  })];
  state = state.map((a, i) => add(a, C[i]));
  for (let r = 0; r < N_ROUNDS_F / 2 - 1; r++) {
    state = state.map(pow5).map((a, i) => add(a, C[(r + 1) * t + i]));
    state = mix(state, M);
  }
  state = state.map(pow5).map((a, i) => add(a, C[(N_ROUNDS_F / 2) * t + i]));
  state = mix(state, PM);
  for (let r = 0; r < nRoundsP; r++) {
    state[0] = add(pow5(state[0]), C[(N_ROUNDS_F / 2 + 1) * t + r]);
    let s0 = 0n;
    for (let j = 0; j < t; j++) s0 += S[(t * 2 - 1) * r + j] * state[j];
    for (let k = 1; k < t; k++) state[k] = (state[k] + state[0] * S[(t * 2 - 1) * r + t + k - 1]) % P;
    state[0] = s0 % P;
  }
  for (let r = 0; r < N_ROUNDS_F / 2 - 1; r++) {
    state = state.map(pow5).map((a, i) => add(a, C[(N_ROUNDS_F / 2 + 1) * t + nRoundsP + r * t + i]));
    state = mix(state, M);
  }
  state = mix(state.map(pow5), M);
  return state[0];
}
export const FIELD_SIZE = P;
export default poseidon;
`;
  const posTmp = join(tmpdir(), `dankswap-poseidon-${process.pid}.mjs`);
  writeFileSync(posTmp, poseidonSrc);
  await esbuild.build({
    entryPoints: [posTmp], outfile: join(OUT, 'poseidon.bundle.js'), bundle: true, format: 'esm',
    minify: true, legalComments: 'inline', target: 'es2020',
    banner: { js: `/*! circomlib Poseidon (BN254, 1-4 inputs), pure BigInt. Constants and algorithm from circomlibjs ${version(nm, 'circomlibjs')}, GPL-3.0. Built by scripts/bundle-vendor.mjs */` },
  });
  // circomlibjs is GPL-3.0 but ships no licence file; reuse the identical GPL-3.0 text from snarkjs.
  writeFileSync(join(OUT, 'poseidon.LICENSE'),
    `poseidon.bundle.js contains constants and code derived from circomlibjs ${version(nm, 'circomlibjs')}\n` +
    'Copyright 2018 0KIMS association. https://github.com/iden3/circomlibjs\n' +
    'Licensed under the GNU General Public License v3.0 (package.json "license": "GPL-3.0"):\n\n' +
    readFileSync(join(nm, 'snarkjs', 'COPYING'), 'utf8'));

  // 3. tweetnacl as an ES module. One line is patched so the PRNG uses globalThis.crypto
  // (browsers, workers and Node 20+) instead of require('crypto'), which ES modules cannot do.
  const naclSrcPath = join(nm, 'tweetnacl', 'nacl-fast.js');
  const naclOrig = readFileSync(naclSrcPath, 'utf8');
  const PRNG_LINE = "var crypto = typeof self !== 'undefined' ? (self.crypto || self.msCrypto) : null;";
  if (!naclOrig.includes(PRNG_LINE)) throw new Error('tweetnacl PRNG line not found; check the version');
  const naclCjs = join(tmpdir(), `dankswap-nacl-fast-${process.pid}.cjs`);
  writeFileSync(naclCjs, naclOrig.replace(PRNG_LINE, "var crypto = typeof globalThis !== 'undefined' ? (globalThis.crypto || globalThis.msCrypto) : null;"));
  const naclTmp = join(tmpdir(), `dankswap-nacl-${process.pid}.mjs`);
  writeFileSync(naclTmp, `import nacl from ${JSON.stringify(naclCjs)};\nexport default nacl;\n`);
  await esbuild.build({
    entryPoints: [naclTmp], outfile: join(OUT, 'tweetnacl.min.js'), bundle: true, format: 'esm', platform: 'neutral',
    minify: true, target: 'es2020', external: ['crypto'],
    banner: { js: `/*! tweetnacl ${version(nm, 'tweetnacl')} (public domain / Unlicense). ES module build by scripts/bundle-vendor.mjs */` },
  });
  copyFileSync(join(nm, 'tweetnacl', 'LICENSE'), join(OUT, 'tweetnacl.LICENSE'));

  for (const f of ['snarkjs.min.js', 'poseidon.bundle.js', 'tweetnacl.min.js']) {
    console.log(`assets/vendor/${f}`, readFileSync(join(OUT, f)).length, 'bytes');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
