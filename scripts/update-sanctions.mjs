#!/usr/bin/env node
// Refreshes assets/js/pool/sanctions.js: the Solana addresses on the US Treasury OFAC SDN list
// ("Digital Currency Address - SOL"). Used by the private pool page (depositor and withdrawal
// recipient) and by the relayer (docs/PHASE2_SPEC.md §9, §10).
//
// Usage: node scripts/update-sanctions.mjs
// Sources, tried in order:
//   1. OFAC SDN XML (official): https://www.treasury.gov/ofac/downloads/sdn.xml
//   2. OFAC Sanctions List Service export of the same file
//   3. github.com/0xB10C/ofac-sanctioned-digital-currency-addresses (daily extraction of the SDN list)
// Run it on a schedule (for example weekly in CI) and redeploy the site and the relayer.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { base58Decode } from '../assets/js/pool/util.js';

const OUT = fileURLToPath(new URL('../assets/js/pool/sanctions.js', import.meta.url));
const SOURCES = [
  { name: 'OFAC SDN XML', url: 'https://www.treasury.gov/ofac/downloads/sdn.xml', parse: parseSdnXml },
  { name: 'OFAC Sanctions List Service', url: 'https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports/SDN.XML', parse: parseSdnXml },
  { name: '0xB10C/ofac-sanctioned-digital-currency-addresses (extracted from the OFAC SDN list)', url: 'https://raw.githubusercontent.com/0xB10C/ofac-sanctioned-digital-currency-addresses/lists/sanctioned_addresses_SOL.txt', parse: parseLines },
];

/** In sdn.xml each address is an <id> with <idType>Digital Currency Address - SOL</idType><idNumber>…</idNumber>. */
export function parseSdnXml(xml) {
  const out = [];
  const re = /<idType>\s*Digital Currency Address - SOL\s*<\/idType>\s*<idNumber>\s*([^<\s]+)\s*<\/idNumber>/g;
  let m;
  while ((m = re.exec(xml))) out.push(m[1]);
  return out;
}

export function parseLines(text) {
  return text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
}

const valid = (a) => {
  const b = base58Decode(a);
  return !!b && b.length === 32;
};

async function main() {
  const errors = [];
  for (const src of SOURCES) {
    try {
      const res = await fetch(src.url, { headers: { 'user-agent': 'dankswap-sanctions-updater' } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const list = [...new Set(src.parse(await res.text()))];
      const bad = list.filter((a) => !valid(a));
      if (bad.length) console.warn('Skipping invalid entries:', bad.join(', '));
      const good = list.filter(valid).sort();
      if (!good.length && src.parse === parseLines) throw new Error('empty list');
      write(good, src);
      console.log(`Wrote ${good.length} addresses from ${src.name}`);
      return;
    } catch (e) {
      errors.push(`${src.name}: ${e.message}`);
      console.warn(`${src.name} failed: ${e.message}`);
    }
  }
  console.error('All sources failed; sanctions.js was not changed.\n' + errors.join('\n'));
  process.exit(1);
}

function write(list, src) {
  const body = `// GENERATED by scripts/update-sanctions.mjs — do not edit by hand.
// Solana addresses on the US Treasury OFAC SDN list ("Digital Currency Address - SOL").
// Checked for the shielding wallet and for withdrawal recipients, in the page and in the relayer.
// Source: ${src.name}
//         ${src.url}

export const SANCTIONS_SOURCE = ${JSON.stringify(src.url)};
export const SANCTIONS_UPDATED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};

export const SANCTIONED_ADDRESSES = Object.freeze(${JSON.stringify(list, null, 2)});

const SET = new Set(SANCTIONED_ADDRESSES);

/** True when the base58 address is on the bundled list. */
export function isSanctioned(address) {
  return typeof address === 'string' && SET.has(address.trim());
}
`;
  writeFileSync(OUT, body);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
